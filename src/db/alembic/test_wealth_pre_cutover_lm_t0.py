"""Tests for the LM-T0 pre-cutover Alembic migration.

REQ: wealth migration pre-cutover widening (LM-T0).

Covers:
- Upgrade: changed_by widened to String(64), cf_scheduled_time added,
  plaid_item CHECK accepts 'pending_oauth' and 'abandoned'.
- Downgrade: changes reversed; downgrade is refused when 'pending_oauth'
  or 'abandoned' rows exist.
- Round-trip: upgrade → downgrade → upgrade on a fixture DB leaves the
  schema consistent.

Technique mirrors ``src/db/test_phase4_extend_enums_migration.py``:
use ``_stamp_at`` to create only the tables the migration touches,
skip running all prior migrations from scratch (which would fail because
historical autogenerated migrations assume pre-existing tables).
"""

from __future__ import annotations

import os
import uuid
from datetime import UTC, datetime
from pathlib import Path

import pytest
import sqlalchemy as sa

# ---------------------------------------------------------------------------
# Revision identifiers
# ---------------------------------------------------------------------------
_PREV_REV = "plaid_p1_init_6a9b"
_THIS_REV = "lmt0_wealth_pre_cutover"

# ---------------------------------------------------------------------------
# DDL for the two tables this migration touches (at the _PREV_REV schema).
# ---------------------------------------------------------------------------

_AUDIT_EVENTS_DDL = """
CREATE TABLE audit_events (
    id VARCHAR NOT NULL,
    transaction_id VARCHAR,
    field_changed VARCHAR NOT NULL,
    old_value TEXT,
    new_value TEXT,
    changed_by VARCHAR(8) NOT NULL,
    changed_at DATETIME NOT NULL,
    entity_id VARCHAR(36),
    entity_type VARCHAR(32),
    PRIMARY KEY (id),
    CONSTRAINT ck_audit_events_exactly_one_target CHECK (
        (transaction_id IS NOT NULL AND entity_id IS NULL AND entity_type IS NULL)
        OR (transaction_id IS NULL AND entity_id IS NOT NULL AND entity_type IS NOT NULL)
    )
)
"""

_PLAID_ITEM_DDL = """
CREATE TABLE plaid_item (
    id VARCHAR(36) NOT NULL,
    item_id VARCHAR(128) NOT NULL,
    institution_id VARCHAR(64) NOT NULL,
    institution_name VARCHAR(128) NOT NULL,
    access_token_encrypted TEXT NOT NULL,
    cursor VARCHAR(255),
    last_sync_at DATETIME,
    last_sync_status VARCHAR(24),
    last_error VARCHAR(64),
    consent_expiration_at DATETIME,
    state_nonce VARCHAR(64),
    state_nonce_expires_at DATETIME,
    status VARCHAR(16) DEFAULT 'active' NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_plaid_item_item_id UNIQUE (item_id),
    CONSTRAINT ck_plaid_item_status CHECK (status IN ('active', 'disconnected')),
    CONSTRAINT ck_plaid_item_last_sync_status CHECK (
        last_sync_status IS NULL
        OR last_sync_status IN ('ok', 'error', 'pending', 'institution_down')
    )
)
"""


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _run_alembic(*args: str) -> None:
    """Invoke Alembic using alembic.config.main — picks up DATABASE_PATH from env."""
    from alembic.config import main as alembic_main

    alembic_main(list(args))


def _stamp_at(db_path: Path, revision: str) -> None:
    """Create a fresh fixture DB stamped at *revision*.

    Creates only the tables the LM-T0 migration touches (audit_events and
    plaid_item), stamps the alembic_version table at *revision*, and sets
    DATABASE_PATH in the process environment so subsequent _run_alembic calls
    use this fixture DB.
    """
    os.environ["DATABASE_PATH"] = str(db_path)
    engine = sa.create_engine(f"sqlite:///{db_path}")
    with engine.begin() as conn:
        conn.execute(
            sa.text(
                "CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL,"
                " CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num))"
            )
        )
        conn.execute(sa.text(f"INSERT INTO alembic_version VALUES ('{revision}')"))
        conn.execute(sa.text(_AUDIT_EVENTS_DDL))
        conn.execute(sa.text(_PLAID_ITEM_DDL))
    engine.dispose()


def _table_info(db_path: Path, table: str) -> dict[str, dict]:
    """Return {column_name: {type, notnull}} for *table* in the fixture DB."""
    engine = sa.create_engine(f"sqlite:///{db_path}")
    with engine.connect() as conn:
        rows = conn.execute(sa.text(f"PRAGMA table_info({table})")).fetchall()
    engine.dispose()
    return {r[1]: {"type": r[2], "notnull": r[3]} for r in rows}


def _table_ddl(db_path: Path, table: str) -> str:
    engine = sa.create_engine(f"sqlite:///{db_path}")
    with engine.connect() as conn:
        row = conn.execute(
            sa.text("SELECT sql FROM sqlite_master WHERE type='table' AND name=:t"),
            {"t": table},
        ).fetchone()
    engine.dispose()
    return row[0] if row else ""


def _now() -> datetime:
    return datetime.now(UTC).replace(tzinfo=None)


