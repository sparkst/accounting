class TestDowngrade:
    """LM-T0 downgrade reverses all changes."""

    def test_downgrade_restores_prev_rev(self, fixture_db: Path) -> None:
        _run_alembic("upgrade", _THIS_REV)
        _run_alembic("downgrade", "-1")
        engine = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine.connect() as conn:
            rev = conn.execute(
                sa.text("SELECT version_num FROM alembic_version")
            ).scalar_one()
        engine.dispose()
        assert rev == _PREV_REV

    def test_downgrade_removes_cf_scheduled_time(self, fixture_db: Path) -> None:
        _run_alembic("upgrade", _THIS_REV)
        _run_alembic("downgrade", "-1")
        cols = _table_info(fixture_db, "audit_events")
        assert "cf_scheduled_time" not in cols

    def test_downgrade_narrows_changed_by(self, fixture_db: Path) -> None:
        _run_alembic("upgrade", _THIS_REV)
        _run_alembic("downgrade", "-1")
        cols = _table_info(fixture_db, "audit_events")
        # After downgrade: VARCHAR(8), not VARCHAR(64)
        assert "64" not in cols["changed_by"]["type"].upper()

    def test_downgrade_restores_narrow_check(self, fixture_db: Path) -> None:
        _run_alembic("upgrade", _THIS_REV)
        _run_alembic("downgrade", "-1")
        ddl = _table_ddl(fixture_db, "plaid_item")
        assert "pending_oauth" not in ddl
        assert "abandoned" not in ddl
        # Original values still present
        assert "active" in ddl
        assert "disconnected" in ddl

    def test_downgrade_refused_when_pending_oauth_exists(
        self, fixture_db: Path
    ) -> None:
        """Downgrade is refused if any plaid_item has status='pending_oauth'."""
        _run_alembic("upgrade", _THIS_REV)
        engine = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine.begin() as conn:
            conn.execute(
                sa.text(
                    "INSERT INTO plaid_item"
                    " (id, item_id, institution_id, institution_name,"
                    "  access_token_encrypted, status, created_at, updated_at)"
                    " VALUES (:id, :item_id, 'ins_test', 'Test Bank',"
                    "  'tok_enc', 'pending_oauth', :now, :now)"
                ),
                {
                    "id": str(uuid.uuid4()),
                    "item_id": "item-block-po",
                    "now": _now(),
                },
            )
        engine.dispose()
        with pytest.raises(RuntimeError, match="refusing to downgrade"):
            _run_alembic("downgrade", "-1")

    def test_downgrade_refused_when_abandoned_exists(
        self, fixture_db: Path
    ) -> None:
        """Downgrade is refused if any plaid_item has status='abandoned'."""
        _run_alembic("upgrade", _THIS_REV)
        engine = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine.begin() as conn:
            conn.execute(
                sa.text(
                    "INSERT INTO plaid_item"
                    " (id, item_id, institution_id, institution_name,"
                    "  access_token_encrypted, status, created_at, updated_at)"
                    " VALUES (:id, :item_id, 'ins_test', 'Test Bank',"
                    "  'tok_enc', 'abandoned', :now, :now)"
                ),
                {
                    "id": str(uuid.uuid4()),
                    "item_id": "item-block-ab",
                    "now": _now(),
                },
            )
        engine.dispose()
        with pytest.raises(RuntimeError, match="refusing to downgrade"):
            _run_alembic("downgrade", "-1")

    def test_downgrade_succeeds_when_only_original_statuses(
        self, fixture_db: Path
    ) -> None:
        """Downgrade proceeds when only 'active'/'disconnected' rows exist."""
        _run_alembic("upgrade", _THIS_REV)
        engine = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine.begin() as conn:
            conn.execute(
                sa.text(
                    "INSERT INTO plaid_item"
                    " (id, item_id, institution_id, institution_name,"
                    "  access_token_encrypted, status, created_at, updated_at)"
                    " VALUES (:id, :item_id, 'ins_test', 'Test Bank',"
                    "  'tok_enc', 'active', :now, :now)"
                ),
                {
                    "id": str(uuid.uuid4()),
                    "item_id": "item-ok-active",
                    "now": _now(),
                },
            )
        engine.dispose()
        _run_alembic("downgrade", "-1")

        engine2 = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine2.connect() as conn:
            rev = conn.execute(
                sa.text("SELECT version_num FROM alembic_version")
            ).scalar_one()
        engine2.dispose()
        assert rev == _PREV_REV


