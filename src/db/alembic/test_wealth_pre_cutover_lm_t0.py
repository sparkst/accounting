class TestRoundTrip:
    """Upgrade → downgrade → upgrade leaves schema consistent."""

    def test_round_trip(self, fixture_db: Path) -> None:
        _run_alembic("upgrade", _THIS_REV)
        _run_alembic("downgrade", "-1")
        _run_alembic("upgrade", _THIS_REV)

        cols = _table_info(fixture_db, "audit_events")
        assert "cf_scheduled_time" in cols
        assert "64" in cols["changed_by"]["type"].upper()

        ddl = _table_ddl(fixture_db, "plaid_item")
        assert "pending_oauth" in ddl
        assert "abandoned" in ddl

        engine = sa.create_engine(f"sqlite:///{fixture_db}")
        with engine.connect() as conn:
            rev = conn.execute(
                sa.text("SELECT version_num FROM alembic_version")
            ).scalar_one()
        engine.dispose()
        assert rev == _THIS_REV
